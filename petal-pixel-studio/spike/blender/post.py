# Turns finished renders into the site's pictures.
# python3 spike/blender/post.py <renders dir> <public/flowers dir>
import datetime, glob, json, os, sys
import numpy as np
from PIL import Image, ImageChops, ImageFilter

renders, public = sys.argv[1], sys.argv[2]
NIGHT = (20, 20, 18)
stamp = datetime.datetime.now(datetime.timezone.utc).isoformat()
rng = np.random.default_rng(1)


def glow(flower):
    """The light that hangs in the air around a lamp, which a render on a clear film has none of."""
    size = flower.width / 1000
    on_black = Image.new("RGBA", flower.size, (0, 0, 0, 255))
    on_black.alpha_composite(flower)
    light = on_black.convert("RGB")
    near = light.filter(ImageFilter.GaussianBlur(12 * size)).point(lambda v: v * 0.18)
    far = light.filter(ImageFilter.GaussianBlur(90 * size)).point(lambda v: v * 0.16)
    return ImageChops.screen(near, far)


def night(path):
    flower = Image.open(path).convert("RGBA")
    ground = Image.new("RGBA", flower.size, (*NIGHT, 255))
    ground.alpha_composite(flower)
    picture = ImageChops.screen(ground.convert("RGB"), glow(flower))
    # A little grain, or the long fade into the night falls into bands once compressed.
    pixels = np.asarray(picture, dtype=np.float32) + rng.normal(0, 1.5, (picture.height, picture.width, 1))
    return Image.fromarray(np.clip(pixels, 0, 255).astype(np.uint8))


for path in sorted(glob.glob(os.path.join(renders, "*.png"))):
    folder, id = os.path.basename(path)[:-4].split("-", 1)
    name = id.replace("-night", "").capitalize()
    dark = folder == "lamps" or id.endswith("-night")
    picture = night(path) if dark else Image.open(path).convert("RGBA")
    target = os.path.join(public, folder, f"{id}.webp")
    picture.save(target, "WEBP", quality=90 if dark else 84, method=6, alpha_quality=92)
    what = f"name {name} at night" if dark else f"name {name}"
    note = {
        "prompt": f"Own render: the Petal Pixel blossom engine's real geometry for {what}, path-traced in Blender Cycles. Not generated by an image model.\n",
        "createdAt": stamp,
    }
    with open(target + ".json", "w") as f:
        json.dump(note, f, indent=2)
    print(f"{folder}/{id}.webp", round(os.path.getsize(target) / 1024), "KB")
