const { chromium } = require(process.argv[2] + '/node_modules/@playwright/test');
const fs = require('fs'); const path = require('path');
const pub = process.argv[2] + '/public/flowers';
const stamp = new Date().toISOString();
const note = (seed) => JSON.stringify({ prompt: `Own render: a real flower scan grown by the Petal Pixel plant, ${seed}, drawn by src/components/flower/blossom/Plant.tsx and captured from the browser. Not generated by an image model.\n`, createdAt: stamp }, null, 2);
const jobs = [];
const only = process.argv[3] ? process.argv[3].split(',') : null;
for (const n of ['Dana', 'Iris', 'Oleg', 'Aisha', 'Maya', 'Ayan', 'Anna']) {
  const id = n.toLowerCase();
  jobs.push({ file: `names/${id}.webp`, q: `name=${n}`, w: 1000, h: 1000, alpha: true, seed: `name ${n}` });
  jobs.push({ file: `names/${id}-night.webp`, q: `name=${n}&night=1`, w: 1000, h: 1000, alpha: false, seed: `name ${n} at night` });
}
for (const n of ['Dana', 'Oleg', 'Aisha', 'Maya', 'Ayan']) jobs.push({ file: `lamps/${n.toLowerCase()}.webp`, q: `name=${n}&night=1&frame=lamp`, w: 864, h: 1248, alpha: false, seed: `name ${n} at night` });
for (const id of ['rose', 'water-lily', 'peony', 'tiger-lily', 'camellia', 'hibiscus']) jobs.push({ file: `grow/${id}.webp`, q: `grower=${id}&frame=thumb`, w: 480, h: 480, alpha: true, seed: `seed grow-${id}-0` });
jobs.push({ file: 'cover.webp', q: 'name=Oleg&night=1&frame=cover', w: 1200, h: 630, alpha: false, seed: 'name Oleg at night' });
jobs.push({ file: 'first.webp', q: 'name=Dana&t=0.3&frame=first', w: 1600, h: 1000, alpha: true, seed: 'name Dana on its stem' });
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
  for (const job of jobs) {
    if (only && !only.some((o) => job.file.includes(o))) continue;
    const page = await browser.newPage({ viewport: { width: job.w, height: job.h }, deviceScaleFactor: 1 });
    page.on('pageerror', (e) => console.log('PAGEERR', String(e).slice(0, 300)));
    await page.goto(`http://localhost:8080/spike/stills.html?${job.q}`);
    await page.waitForFunction(() => window.__ready === true && window.__head === true, null, { timeout: 90000 });
    await page.waitForTimeout(600);
    const png = await page.screenshot({ omitBackground: job.alpha });
    const webp = await page.evaluate(async ([b64, quality]) => {
      const img = new Image(); img.src = 'data:image/png;base64,' + b64; await img.decode();
      const c = document.createElement('canvas'); c.width = img.width; c.height = img.height;
      c.getContext('2d').drawImage(img, 0, 0);
      const blob = await new Promise((r) => c.toBlob(r, 'image/webp', quality));
      const buf = new Uint8Array(await blob.arrayBuffer());
      let s = ''; for (let i = 0; i < buf.length; i += 1) s += String.fromCharCode(buf[i]);
      return btoa(s);
    }, [png.toString('base64'), 0.82]);
    const out = Buffer.from(webp, 'base64');
    const file = path.join(pub, job.file);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, out);
    fs.writeFileSync(file + '.json', note(job.seed));
    console.log(job.file, Math.round(out.length / 1024) + 'KB');
    await page.close();
  }
  await browser.close();
})().catch((e) => { console.error(String(e).slice(0, 300)); process.exit(1); });
